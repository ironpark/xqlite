-- Writes src/dialect/postgres/systypes.zig from PostgreSQL 18: every row
-- of pg_type in pg_catalog and information_schema, and pg_range's rows.
-- pgcatalog.zig shows those xqlite does not make itself (its built-in
-- types, information_schema's domains, the row types of the system
-- relations it has): the other built-in types, the range types, and the
-- row types of the relations it has not, with their arrays.
--
--   podman exec -i xq-pg psql -U postgres -d postgres -At \
--     < tools/dialect/pg-systypes.sql > src/dialect/postgres/systypes.zig
--   zig fmt src/dialect/postgres/systypes.zig
WITH lines(k, z) AS (
  SELECT 0, '//! PostgreSQL 18''s rows of pg_type (in pg_catalog and information_schema)'
  UNION ALL SELECT 1, '//! and of pg_range (pgcatalog.zig). Generated by tools/dialect/pg-systypes.sql'
  UNION ALL SELECT 2, '//! from ' || version() || '.'
  UNION ALL SELECT 3, E'\nconst pgc = @import("pgcatalog.zig");\n\npub const types = [_]pgc.SysType{'
  UNION ALL SELECT 4, string_agg(format('.{ .oid = %s, .name = "%s", .nsp = %s, .len = %s, .byval = %s, .typtype = ''%s'', .cat = ''%s'', .preferred = %s, .relid = %s, .subscript = "%s", .elem = %s, .array = %s, .input = "%s", .output = "%s", .recv = "%s", .send = "%s", .modin = "%s", .modout = "%s", .analyze = "%s", .@"align" = ''%s'', .storage = ''%s'', .basetype = %s, .typmod = %s, .ndims = %s, .coll = %s },',
      t.oid, t.typname, t.typnamespace, t.typlen, t.typbyval::text, t.typtype, t.typcategory, t.typispreferred::text, t.typrelid,
      t.typsubscript::text, t.typelem, t.typarray, t.typinput::text, t.typoutput::text, t.typreceive::text, t.typsend::text,
      t.typmodin::text, t.typmodout::text, t.typanalyze::text, t.typalign, t.typstorage, t.typbasetype, t.typtypmod, t.typndims, t.typcollation), E'\n'
      ORDER BY t.oid)
    FROM pg_type t WHERE t.typnamespace IN ('pg_catalog'::regnamespace, 'information_schema'::regnamespace)
  UNION ALL SELECT 5, E'};\n\npub const ranges = [_]pgc.SysRange{'
  UNION ALL SELECT 6, string_agg(format('.{ .typ = %s, .subtype = %s, .multi = %s, .coll = %s, .opc = %s, .canonical = "%s", .subdiff = "%s" },',
      r.rngtypid, r.rngsubtype, r.rngmultitypid, r.rngcollation, r.rngsubopc, r.rngcanonical::text, r.rngsubdiff::text), E'\n'
      ORDER BY r.rngtypid)
    FROM pg_range r
  UNION ALL SELECT 7, '};'
)
SELECT z FROM lines ORDER BY k;
