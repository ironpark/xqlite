//! Converts the parser lemon generates from SQLite's parse.y into Zig:
//! token codes (parse.h), the LALR(1) tables, symbol and rule names
//! (parse.c), and the keyword list (keywords.c output).
//!
//!     zig run lemon2zig.zig -- parse.c parse.h keywords.txt VERSION > grammar.zig
//!
//! Only tables are converted. The reduce actions are written by hand in
//! src/parse/parser.zig, keyed by rule text, so a changed grammar shows up
//! as a compile error rather than a silently misnumbered action.

const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(gpa);
    if (args.len != 5) {
        std.debug.print("usage: lemon2zig parse.c parse.h keywords.txt version\n", .{});
        std.process.exit(2);
    }
    const cwd = std.Io.Dir.cwd();
    const parse_c = try cwd.readFileAlloc(io, args[1], gpa, .limited(16 << 20));
    const parse_h = try cwd.readFileAlloc(io, args[2], gpa, .limited(1 << 20));
    const keywords = try cwd.readFileAlloc(io, args[3], gpa, .limited(1 << 20));
    const version = std.mem.trim(u8, args[4], " \n");

    var buf: [1 << 16]u8 = undefined;
    var fw: std.Io.File.Writer = .init(.stdout(), io, &buf);
    const w = &fw.interface;

    try w.print(
        \\//! SQLite {s} grammar tables, generated by `xqt gen parser` from
        \\//! parse.y with lemon. Do not edit.
        \\
        \\pub const Keyword = struct {{ name: []const u8, code: u8 }};
        \\
        \\/// Token codes (TK_*). Codes past the last real token are used only as
        \\/// expression node types.
        \\pub const TK = struct {{
        \\
    , .{version});
    var lines = std.mem.splitScalar(u8, parse_h, '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeAny(u8, line, " \t");
        if (!std.mem.eql(u8, it.next() orelse continue, "#define")) continue;
        const name = it.next() orelse continue;
        const value = it.next() orelse continue;
        if (!std.mem.startsWith(u8, name, "TK_")) continue;
        try w.print("    pub const {s} = {s};\n", .{ name[3..], value });
    }
    try w.writeAll("};\n\n");

    const constants = [_][]const u8{
        "YYNOCODE",           "YYWILDCARD",         "YYNSTATE",          "YYNRULE",
        "YYNRULE_WITH_ACTION", "YYNTOKEN",          "YY_MAX_SHIFT",      "YY_MIN_SHIFTREDUCE",
        "YY_MAX_SHIFTREDUCE", "YY_ERROR_ACTION",    "YY_ACCEPT_ACTION",  "YY_NO_ACTION",
        "YY_MIN_REDUCE",      "YY_MAX_REDUCE",      "YY_ACTTAB_COUNT",   "YY_SHIFT_COUNT",
        "YY_SHIFT_MIN",       "YY_SHIFT_MAX",       "YY_REDUCE_COUNT",   "YY_REDUCE_MIN",
        "YY_REDUCE_MAX",      "YYSTACKDEPTH",
    };
    for (constants) |name| {
        const value = try define(parse_c, name);
        try w.print("pub const {s} = {s};\n", .{ name, value });
    }
    try w.writeAll("\n");

    const arrays = [_]struct { c: []const u8, zig: []const u8, ty: []const u8 }{
        .{ .c = "yy_action", .zig = "yy_action", .ty = "u16" },
        .{ .c = "yy_lookahead", .zig = "yy_lookahead", .ty = "u16" },
        .{ .c = "yy_shift_ofst", .zig = "yy_shift_ofst", .ty = "u16" },
        .{ .c = "yy_reduce_ofst", .zig = "yy_reduce_ofst", .ty = "i16" },
        .{ .c = "yy_default", .zig = "yy_default", .ty = "u16" },
        .{ .c = "yyFallback", .zig = "yy_fallback", .ty = "u16" },
        .{ .c = "yyRuleInfoLhs", .zig = "yy_rule_info_lhs", .ty = "u16" },
        .{ .c = "yyRuleInfoNRhs", .zig = "yy_rule_info_nrhs", .ty = "i8" },
    };
    for (arrays) |a| {
        const body = try arrayBody(gpa, parse_c, a.c);
        try w.print("pub const {s} = [_]{s}{{", .{ a.zig, a.ty });
        var n: usize = 0;
        var items = std.mem.tokenizeAny(u8, body, ", \n\t");
        while (items.next()) |item| : (n += 1) {
            if (n % 16 == 0) try w.writeAll("\n   ");
            try w.print(" {s},", .{item});
        }
        try w.writeAll("\n};\n\n");
    }

    for ([_][2][]const u8{ .{ "yyTokenName", "symbol_names" }, .{ "yyRuleName", "rule_names" } }) |a| {
        const body = try arrayBody(gpa, parse_c, a[0]);
        try w.print("pub const {s} = [_][]const u8{{\n", .{a[1]});
        var rest = body;
        while (std.mem.indexOfScalar(u8, rest, '"')) |start| {
            const end = std.mem.indexOfScalarPos(u8, rest, start + 1, '"') orelse return error.BadString;
            try w.print("    \"{s}\",\n", .{rest[start + 1 .. end]});
            rest = rest[end + 1 ..];
        }
        try w.writeAll("};\n\n");
    }

    // The rules as an enum named by their text, so that the action switch
    // in parser.zig must handle every rule.
    {
        const body = try arrayBody(gpa, parse_c, "yyRuleName");
        try w.writeAll("/// Grammar rules, named by their text.\npub const Rule = enum(u16) {\n");
        var rest = body;
        var n: usize = 0;
        while (std.mem.indexOfScalar(u8, rest, '"')) |start| : (n += 1) {
            const end = std.mem.indexOfScalarPos(u8, rest, start + 1, '"') orelse return error.BadString;
            try w.print("    @\"{s}\" = {d},\n", .{ rest[start + 1 .. end], n });
            rest = rest[end + 1 ..];
        }
        try w.writeAll("};\n\n");
    }

    try w.writeAll("pub const keywords = [_]Keyword{\n");
    var kw_lines = std.mem.tokenizeScalar(u8, keywords, '\n');
    while (kw_lines.next()) |line| {
        var it = std.mem.tokenizeScalar(u8, line, ' ');
        const name = it.next() orelse continue;
        const code = it.next() orelse return error.BadKeyword;
        try w.print("    .{{ .name = \"{s}\", .code = {s} }},\n", .{ name, code });
    }
    try w.writeAll("};\n");
    try w.flush();
}

/// The value of `#define name value` in `src`, without parentheses.
fn define(src: []const u8, name: []const u8) ![]const u8 {
    var lines = std.mem.splitScalar(u8, src, '\n');
    while (lines.next()) |line| {
        var it = std.mem.tokenizeAny(u8, line, " \t");
        if (!std.mem.eql(u8, it.next() orelse continue, "#define")) continue;
        if (!std.mem.eql(u8, it.next() orelse continue, name)) continue;
        return std.mem.trim(u8, it.rest(), " ()");
    }
    std.debug.print("missing #define {s}\n", .{name});
    return error.MissingDefine;
}

/// The text between the braces of `name[] = { ... };`, comments removed.
fn arrayBody(gpa: std.mem.Allocator, src: []const u8, name: []const u8) ![]const u8 {
    const decl = try std.fmt.allocPrint(gpa, " {s}[] = {{", .{name});
    const start = (std.mem.indexOf(u8, src, decl) orelse {
        std.debug.print("missing array {s}\n", .{name});
        return error.MissingArray;
    }) + decl.len;
    const end = std.mem.indexOfPos(u8, src, start, "};") orelse return error.MissingArray;
    var out: std.ArrayList(u8) = .empty;
    var rest = src[start..end];
    while (std.mem.indexOf(u8, rest, "/*")) |c| {
        try out.appendSlice(gpa, rest[0..c]);
        const close = std.mem.indexOfPos(u8, rest, c, "*/") orelse return error.BadComment;
        rest = rest[close + 2 ..];
    }
    try out.appendSlice(gpa, rest);
    return out.items;
}
