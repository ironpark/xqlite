-- Writes src/dialect/postgres/syscatalog.zig from PostgreSQL 18: the
-- pg_class, pg_attribute, pg_index and pg_constraint rows of the system
-- relations xqlite has (catalog_views.zig), and of their indexes.
--
--   podman exec -i xq-pg psql -U postgres -d postgres -At \
--     < tools/dialect/pg-syscatalog.sql > src/dialect/postgres/syscatalog.zig
--   zig fmt src/dialect/postgres/syscatalog.zig
--
-- Add a relation to `names` below when catalog_views.zig has a new one.
WITH names(n) AS (VALUES
  ('information_schema.tables'), ('information_schema.columns'), ('information_schema.views'),
  ('information_schema.schemata'), ('information_schema.sequences'), ('information_schema.table_constraints'),
  ('information_schema.key_column_usage'), ('information_schema.referential_constraints'),
  ('information_schema.check_constraints'), ('information_schema.constraint_column_usage'),
  ('pg_tables'), ('pg_views'), ('pg_indexes'), ('pg_sequences'), ('pg_namespace'), ('pg_class'),
  ('pg_attribute'), ('pg_type'), ('pg_index'), ('pg_constraint'), ('pg_attrdef'), ('pg_sequence'),
  ('pg_depend'), ('pg_proc'), ('pg_database'), ('pg_roles'), ('pg_authid'), ('pg_user'), ('pg_am'),
  ('pg_opclass'), ('pg_opfamily'), ('pg_statio_all_tables'), ('pg_statio_user_tables'),
  ('pg_tablespace'), ('pg_collation'), ('pg_language'), ('pg_settings'), ('pg_description'),
  ('pg_shdescription'), ('pg_inherits'), ('pg_trigger'), ('pg_policy'), ('pg_rewrite'),
  ('pg_statistic_ext'), ('pg_publication'), ('pg_publication_rel'), ('pg_publication_namespace'),
  ('pg_enum'), ('pg_extension'), ('pg_auth_members'), ('pg_partitioned_table'), ('pg_foreign_table'),
  ('pg_matviews'), ('pg_range'), ('pg_event_trigger'), ('pg_available_extensions'), ('pg_cursors')
), tabs AS (
  SELECT ('pg_catalog.' || n)::regclass::oid AS oid FROM names WHERE n NOT LIKE '%.%'
  UNION ALL SELECT n::regclass::oid FROM names WHERE n LIKE '%.%'
), rels AS (
  SELECT c.* FROM pg_class c WHERE c.oid IN (SELECT oid FROM tabs)
  UNION ALL SELECT c.* FROM pg_class c JOIN pg_index i ON i.indexrelid = c.oid WHERE i.indrelid IN (SELECT oid FROM tabs)
), lines(k, z) AS (
  SELECT 0, '//! PostgreSQL 18''s rows of the system relations xqlite has, and of their'
  UNION ALL SELECT 1, '//! indexes (pgcatalog.zig). Generated by tools/dialect/pg-syscatalog.sql'
  UNION ALL SELECT 2, '//! from ' || version() || '.'
  UNION ALL SELECT 3, E'\nconst pgc = @import("pgcatalog.zig");\n\npub const rels = [_]pgc.Rel{'
  UNION ALL SELECT 4, string_agg(format('.{ .oid = %s, .name = "%s", .nsp = %s, .kind = ''%s'', .db = "", .sqlite_name = "", .rowtype = %s, .natts = %s, .has_index = %s, .shared = %s, .acl = %s },',
      c.oid, c.relname, c.relnamespace, c.relkind, c.reltype, c.relnatts, c.relhasindex::text, c.relisshared::text, coalesce('"' || c.relacl::text || '"', 'null')), E'\n'
      ORDER BY c.relnamespace, c.relname)
    FROM rels c
  UNION ALL SELECT 5, E'};\n\npub const attrs = [_]pgc.Attr{'
  UNION ALL SELECT 6, string_agg(format('.{ .rel = %s, .name = "%s", .num = %s, .type_oid = %s, .typmod = %s, .notnull = %s, .collation = %s },',
      a.attrelid, a.attname, a.attnum, a.atttypid, a.atttypmod, a.attnotnull::text, a.attcollation), E'\n'
      ORDER BY c.relnamespace, c.relname, a.attnum)
    FROM pg_attribute a JOIN rels c ON c.oid = a.attrelid WHERE a.attnum > 0
  UNION ALL SELECT 7, E'};\n\npub const indexes = [_]pgc.IndexRow{'
  UNION ALL SELECT 8, string_agg(format('.{ .rel = %s, .table = %s, .unique = %s, .primary = %s, .keys = &.{ %s }, .desc = &.{ %s }, .coldefs = &.{ %s } },',
      i.indexrelid, i.indrelid, i.indisunique::text, i.indisprimary::text,
      array_to_string(i.indkey::int2[], ', '),
      (SELECT string_agg('false', ', ') FROM generate_series(1, i.indnatts)),
      (SELECT string_agg('"' || pg_get_indexdef(i.indexrelid, k, false) || '"', ', ' ORDER BY k) FROM generate_series(1, i.indnatts) k)), E'\n'
      ORDER BY t.relnamespace, t.relname, c.relname)
    FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid JOIN pg_class t ON t.oid = i.indrelid WHERE i.indrelid IN (SELECT oid FROM tabs)
  UNION ALL SELECT 9, E'};\n\npub const cons = [_]pgc.Con{'
  UNION ALL SELECT 10, string_agg(format('.{ .oid = %s, .name = "%s", .nsp = %s, .type = ''%s'', .rel = %s, .index = %s, .keys = &.{ %s } },',
      k.oid, k.conname, k.connamespace, k.contype, k.conrelid, k.conindid, array_to_string(k.conkey, ', ')), E'\n'
      ORDER BY t.relnamespace, t.relname,
        CASE k.contype WHEN 'n' THEN 0 WHEN 'c' THEN 1 WHEN 'p' THEN 2 WHEN 'u' THEN 3 ELSE 4 END, k.conname)
    FROM pg_constraint k JOIN pg_class t ON t.oid = k.conrelid WHERE k.conrelid IN (SELECT oid FROM tabs)
  UNION ALL SELECT 11, '};'
)
SELECT z FROM lines ORDER BY k;
