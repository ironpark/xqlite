//! The Oracle dialect against sqlite3: a database written by `xqlite sql`
//! in the Oracle dialect (STRICT tables with the checks of Oracle's
//! types, an identity column and a sequence, the xq_catalog/xq_sequence
//! catalog, views, indexes, MERGE, a JSON column, committed with COMMIT)
//! must pass
//! sqlite3's integrity check, and sqlite3 and xqlite (in the SQLite
//! dialect) must read the same rows and schema from it.

const std = @import("std");
const xqt = @import("xqt");
const Check = xqt.Check;
const BaseDb = @import("base_db.zig");

pub const name = "oracle";
pub const about = "an Oracle-dialect database read by sqlite3: integrity, rows, STRICT types";

pub fn register(s: *xqt.Suite) !void {
    const base = try s.arena.allocator().create(BaseDb);
    base.* = .{ .build = build };
    try s.add("integrity_check and foreign_key_check", integrity, .{base});
    try s.add("results", results, .{base});
    for (bad) |stmt| try s.add(try std.fmt.allocPrint(s.arena.allocator(), "sqlite3 rejects: {s}", .{stmt}), rejects, .{ base, stmt });
    try s.add("read back", readBack, .{base});
    try s.add("schema tables", schemaTables, .{base});
}

const db = "oracle.db";

const script =
    \\.dialect oracle
    \\CREATE TABLE account (
    \\  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    \\  email VARCHAR2(80) NOT NULL UNIQUE,
    \\  active NUMBER(1) DEFAULT 1 NOT NULL,
    \\  balance NUMBER(12,2) DEFAULT 0 CHECK (balance >= 0),
    \\  created DATE DEFAULT SYSDATE,
    \\  note VARCHAR2(20)
    \\);
    \\CREATE TABLE entry (
    \\  id NUMBER(10) PRIMARY KEY,
    \\  account_id NUMBER REFERENCES account (id) ON DELETE CASCADE,
    \\  amount NUMBER(8) NOT NULL,
    \\  memo CHAR(4),
    \\  booked TIMESTAMP(3)
    \\);
    \\CREATE INDEX entry_account ON entry (account_id, amount DESC);
    \\CREATE UNIQUE INDEX account_upper_email ON account (UPPER(email));
    \\CREATE SEQUENCE entry_seq START WITH 1 INCREMENT BY 1 NOCACHE;
    \\INSERT INTO account (email, balance, note)
    \\  WITH n (i) AS (SELECT 1 FROM dual UNION ALL SELECT i + 1 FROM n WHERE i < 300)
    \\  SELECT 'user' || i || '@example.com', i * 1.5, CASE WHEN MOD(i, 2) = 0 THEN 'even' ELSE '' END FROM n;
    \\INSERT INTO entry (id, account_id, amount, memo, booked)
    \\  WITH n (i) AS (SELECT 1 FROM dual UNION ALL SELECT i + 1 FROM n WHERE i < 2000)
    \\  SELECT entry_seq.NEXTVAL, 1 + MOD(i, 300), i, 'm' || MOD(i, 10), TIMESTAMP '2024-01-01 00:00:00' + i FROM n;
    \\UPDATE account SET active = 0 WHERE MOD(id, 7) = 0;
    \\DELETE FROM entry WHERE account_id IN (SELECT id FROM account WHERE active = 0);
    \\MERGE INTO account a USING (SELECT 'user1@example.com' email FROM dual UNION ALL SELECT 'new@example.com' FROM dual) s
    \\  ON (a.email = s.email)
    \\  WHEN MATCHED THEN UPDATE SET a.balance = a.balance + 1
    \\  WHEN NOT MATCHED THEN INSERT (email) VALUES (s.email);
    \\CREATE VIEW totals AS SELECT a.email, count(e.id) AS n, sum(e.amount) AS total FROM account a, entry e WHERE e.account_id(+) = a.id GROUP BY a.email;
    \\ALTER TABLE entry ADD (tag VARCHAR2(8));
    \\COMMENT ON TABLE entry IS 'ledger entries';
    \\CREATE TABLE doc (id NUMBER PRIMARY KEY, body JSON, meta VARCHAR2(100));
    \\INSERT INTO doc VALUES (1, '{a : 1.50, "tags" : ["x", "y"]}', JSON_OBJECT('n' VALUE 1, 'd' VALUE DATE '2024-01-02'));
    \\INSERT INTO doc VALUES (2, JSON_ARRAY(1, 'two', NULL NULL ON NULL), NULL);
    \\UPDATE doc SET body = JSON_TRANSFORM(body, SET '$.b' = TRUE) WHERE id = 1;
    \\CREATE TABLE gone (x NUMBER);
    \\DROP TABLE gone PURGE;
    \\CREATE USER sales IDENTIFIED BY pw QUOTA UNLIMITED ON users;
    \\CREATE TABLE sales.orders (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id NUMBER REFERENCES account (id), amount NUMBER(8) CHECK (amount > 0));
    \\CREATE INDEX sales.orders_account ON sales.orders (account_id);
    \\INSERT INTO sales.orders (account_id, amount)
    \\  WITH n (i) AS (SELECT 1 FROM dual UNION ALL SELECT i + 1 FROM n WHERE i < 50)
    \\  SELECT i, i * 2 FROM n;
    \\CREATE VIEW sales.big AS SELECT o.id, o.amount FROM sales.orders o WHERE o.amount > 50;
    \\CREATE USER tmp IDENTIFIED BY pw;
    \\CREATE TABLE tmp.x (a NUMBER);
    \\DROP USER tmp CASCADE;
    \\COMMIT;
    \\
;

const queries =
    \\SELECT count(*), sum(id), sum(balance), sum(active), count(note) FROM account;
    \\SELECT count(*), sum(amount), min(memo), max(memo), min(booked), max(booked) FROM entry;
    \\SELECT * FROM totals ORDER BY total DESC, email LIMIT 5;
    \\SELECT id, body, meta, json_extract(body, '$.a'), json_valid(body) FROM doc ORDER BY id;
    \\SELECT count(*), sum(amount) FROM "SALES.ORDERS";
    \\SELECT count(*), sum(amount) FROM "SALES.BIG";
    \\SELECT * FROM xq_catalog ORDER BY tbl, col, key;
    \\SELECT * FROM xq_sequence ORDER BY name;
    \\SELECT type, name, tbl_name, sql FROM sqlite_schema ORDER BY name;
;

/// sqlite3 enforces the STRICT types and the checks of the Oracle types.
const bad = [_][]const u8{
    "INSERT INTO entry(id, account_id, amount) VALUES (9001, 1, 'x')",
    "INSERT INTO entry(id, account_id, amount, tag) VALUES (9002, 1, 1, 'too long tag')",
    "INSERT INTO entry(id, account_id, amount) VALUES (9003, 1, 123456789)",
    "UPDATE account SET balance = 12345678901 WHERE id = 1",
    "INSERT INTO doc(id, body) VALUES (9, '{a:1}')",
};

fn build(c: *Check, file: []const u8) !void {
    _ = try c.runOk(&.{ c.cfg.xq, "sql", file }, .{ .stdin = script });
}

fn integrity(c: *Check, base: *BaseDb) !void {
    try base.get(c, db);
    const ok = std.mem.trimEnd(u8, try c.sqlite3(db, "PRAGMA integrity_check"), "\n");
    _ = c.expect(std.mem.eql(u8, ok, "ok"), "integrity_check: {s}", .{ok});
    const fk = std.mem.trimEnd(u8, try c.sqlite3(db, "PRAGMA foreign_key_check"), "\n");
    _ = c.expect(fk.len == 0, "foreign_key_check: {s}", .{fk});
}

fn results(c: *Check, base: *BaseDb) !void {
    try base.get(c, db);
    const x = try c.xqSql(db, queries);
    const s = try c.sqlite3(db, queries);
    _ = c.expectSame("results", "xqlite", x, "sqlite3", s);
}

fn rejects(c: *Check, base: *BaseDb, stmt: []const u8) !void {
    try base.get(c, db);
    const r = try c.run(&.{ c.cfg.sqlite3, db, stmt }, .{});
    _ = c.expect(!r.ok(), "sqlite3 accepted: {s}", .{stmt});
}

/// The Oracle dialect reads back what sqlite3 changed, and its implicit
/// transaction keeps nothing without a COMMIT (the identity value taken
/// by the rolled back INSERT, 302, comes again: the MERGE took 301).
fn readBack(c: *Check, base: *BaseDb) !void {
    try base.get(c, db);
    _ = try c.sqlite3(db, "UPDATE account SET balance = balance + 1 WHERE id = 2");
    const out = try c.runOk(&.{ c.cfg.xq, "sql", db }, .{ .stdin = ".dialect oracle\nSELECT balance FROM account WHERE id = 2;\nINSERT INTO account (email) VALUES (q'[x@y]');\nSELECT max(id) FROM account;\nROLLBACK;\nINSERT INTO account (email) VALUES ('z@y');\nCOMMIT;\nSELECT max(id), count(*) FROM account;\n" });
    const got = std.mem.trimEnd(u8, out, "\n");
    _ = c.expect(std.mem.eql(u8, got, "4\n302\n302|302"), "read back: {s}", .{got});
}

/// A table of user SALES (CREATE USER) is the table "SALES.ORDERS" of
/// main: sqlite3 lists it, reads and writes it, and the Oracle dialect
/// reads sqlite3's row as sales.orders (and as orders with
/// CURRENT_SCHEMA = sales).
fn schemaTables(c: *Check, base: *BaseDb) !void {
    try base.get(c, db);
    const tables = try c.sqlite3(db, ".tables");
    _ = c.expect(std.mem.indexOf(u8, tables, "SALES.ORDERS") != null and std.mem.indexOf(u8, tables, "SALES.BIG") != null, ".tables: {s}", .{tables});
    _ = c.expect(std.mem.indexOf(u8, tables, "TMP.X") == null, ".tables still lists TMP.X: {s}", .{tables});
    _ = try c.sqlite3(db, "INSERT INTO \"SALES.ORDERS\" (ID, ACCOUNT_ID, AMOUNT) VALUES (1000, 1, 7)");
    const out = try c.runOk(&.{ c.cfg.xq, "sql", db }, .{ .stdin = ".dialect oracle\nSELECT amount FROM sales.orders WHERE id = 1000;\nALTER SESSION SET CURRENT_SCHEMA = sales;\nSELECT count(*) FROM orders;\nSELECT count(*) FROM all_tables WHERE owner = 'SALES';\n" });
    const got = std.mem.trimEnd(u8, out, "\n");
    _ = c.expect(std.mem.eql(u8, got, "7\n51\n1"), "schema read back: {s}", .{got});
}
